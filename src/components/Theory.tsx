import { useEffect, useRef } from 'react'

export function Theory({ onHome, onStart }: { onHome: () => void; onStart: () => void }) {
  const heading = useRef<HTMLHeadingElement>(null)
  useEffect(() => { heading.current?.focus() }, [])

  return (
    <article className="card theory" aria-labelledby="theory-heading">
      <span className="eyebrow">Разберёмся вместе</span>
      <h2 id="theory-heading" ref={heading} tabIndex={-1}>Теорема Виета</h2>
      <p className="intro">Коэффициенты уравнения подсказывают, какие два числа нужно найти. Изучи правило и раскрой примеры, чтобы увидеть каждый шаг.</p>

      <section aria-labelledby="reduced-heading">
        <h3 id="reduced-heading">1. Что значит «приведённое»?</h3>
        <p>Квадратное уравнение имеет вид ax² + bx + c = 0, где a ≠ 0. Оно называется <strong>приведённым</strong>, если коэффициент при x² равен 1:</p>
        <p className="formula">x² + px + q = 0</p>
        <p>Здесь p — коэффициент при x, а q — свободный член. Например, в x² − 5x + 6 = 0 получаем p = −5 и q = 6. Знак входит в коэффициент!</p>
        <p>Если перед x² стоит другое число, можно разделить на него всё уравнение: 2x² − 6x + 4 = 0 превращается в x² − 3x + 2 = 0.</p>
      </section>

      <section aria-labelledby="vieta-heading">
        <h3 id="vieta-heading">2. Сумма и произведение корней</h3>
        <p>Корень — число, при подстановке которого вместо x получается верное равенство. Если x₁ и x₂ — действительные корни приведённого квадратного уравнения, то:</p>
        <div className="notice hint">
          <p className="formula">x₁ + x₂ = −p</p>
          <p className="formula">x₁ · x₂ = q</p>
          <p>Сумма корней равна коэффициенту при x с противоположным знаком, а произведение — свободному члену.</p>
        </div>
        <p>Верно и обратное: если два числа имеют сумму −p и произведение q, они являются корнями этого уравнения. Поэтому можно подбирать пары множителей числа q и проверять их сумму.</p>
        <p>Не каждое квадратное уравнение имеет действительные или целые корни. В нашей тренировке целые действительные корни гарантированы. Если корни совпадают, в формулах одно и то же число учитывается дважды.</p>
      </section>

      <section aria-labelledby="examples-heading">
        <h3 id="examples-heading">3. Четыре примера</h3>
        <p className="muted">Нажми на пример или выдели его клавишей Tab и нажми Enter, чтобы раскрыть разбор.</p>
        <div className="theory-examples">
          <details>
            <summary>Положительные корни: x² − 5x + 6 = 0</summary>
            <ol>
              <li>Выпишем коэффициенты: p = −5, q = 6.</li>
              <li>Нужны числа с суммой −(−5) = 5 и произведением 6.</li>
              <li>Положительные пары множителей: 1 и 6 (сумма 7), 2 и 3 (сумма 5). Подходит вторая пара.</li>
              <li>Проверим оба условия: 2 + 3 = 5, 2 · 3 = 6.</li>
            </ol>
            <p className="example-answer">Ответ: x₁ = 2, x₂ = 3.</p>
          </details>
          <details>
            <summary>Отрицательные корни: x² + 7x + 12 = 0</summary>
            <ol>
              <li>Здесь p = 7, q = 12. Сумма корней равна −7, произведение равно 12.</li>
              <li>Положительное произведение означает одинаковые знаки. Отрицательная сумма показывает, что оба корня отрицательные.</li>
              <li>Проверим пары: −1 и −12 дают сумму −13; −2 и −6 дают −8; −3 и −4 дают −7.</li>
              <li>Оба условия выполнены: (−3) + (−4) = −7, (−3) · (−4) = 12.</li>
            </ol>
            <p className="example-answer">Ответ: x₁ = −3, x₂ = −4.</p>
          </details>
          <details>
            <summary>Совпадающие корни: x² − 6x + 9 = 0</summary>
            <ol>
              <li>Коэффициенты p = −6, q = 9. Нужны сумма 6 и произведение 9.</li>
              <li>Пара 1 и 9 даёт сумму 10, а пара 3 и 3 — нужную сумму 6.</li>
              <li>Проверяем: 3 + 3 = 6, 3 · 3 = 9. Уравнение можно записать как (x − 3)² = 0.</li>
              <li>Это один различный корень, повторяющийся дважды. В два поля тренажёра нужно ввести 3 и 3.</li>
            </ol>
            <p className="example-answer">Ответ: x₁ = x₂ = 3.</p>
          </details>
          <details>
            <summary>Нулевой корень: x² + 4x = 0</summary>
            <ol>
              <li>Свободный член отсутствует, значит q = 0. Коэффициент p = 4.</li>
              <li>Произведение корней равно 0: хотя бы один корень равен нулю.</li>
              <li>Сумма равна −4. Если один корень 0, второй должен быть −4.</li>
              <li>Проверим: 0 + (−4) = −4, 0 · (−4) = 0. Также можно вынести x за скобки: x(x + 4) = 0.</li>
            </ol>
            <p className="example-answer">Ответ: x₁ = 0, x₂ = −4.</p>
          </details>
        </div>
      </section>

      <section aria-labelledby="mistakes-heading">
        <h3 id="mistakes-heading">4. Где чаще всего ошибаются?</h3>
        <ul className="theory-list">
          <li><strong>Забывают минус перед p.</strong> В x² − 5x + 6 = 0 коэффициент p = −5, поэтому сумма равна 5, а не −5.</li>
          <li><strong>Меняют знак q.</strong> Произведение равно самому q. В x² + x − 6 = 0 оно равно −6: корни −3 и 2 имеют разные знаки и сумму −1.</li>
          <li><strong>Считают, что положительное q означает положительные корни.</strong> Оно означает одинаковые знаки ненулевых корней; знак суммы помогает выбрать между двумя положительными и двумя отрицательными.</li>
          <li><strong>Проверяют только произведение.</strong> Пара должна одновременно удовлетворять двум условиям — и сумме, и произведению.</li>
          <li><strong>Теряют нулевые коэффициенты.</strong> В x² − 9 = 0 имеем p = 0, поэтому сумма корней равна 0: подходят −3 и 3. В x² = 0 оба корня равны 0.</li>
          <li><strong>Применяют формулы к неприведённому уравнению.</strong> Сначала раздели все члены на коэффициент при x², чтобы он стал равен 1.</li>
        </ul>
      </section>
      <div className="theory-navigation">
        <button type="button" className="secondary" onClick={onHome}>На главную</button>
        <button type="button" className="primary" onClick={onStart}>Начать тренировку</button>
      </div>
    </article>
  )
}
